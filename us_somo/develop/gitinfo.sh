#!/bin/sh
# Records the git branch and commit this tree is built from in include/us_somo_gitinfo.h, so a
# running SOMO can say which build it is: the startup text shows both, and the main window title
# shows the branch (see US_Hydrodyn).
#
# libus_somo.pro runs this once at qmake time, so the header exists when qmake scans dependencies,
# and again at make time through a FORCE target, so running make on the library after a checkout
# or pull picks up the change even without re-running qmake. The header is rewritten only when its
# content changes, so an unchanged checkout does not trigger a recompile. Outside a git checkout,
# or without git, both fields read "unknown". The header is generated: it is gitignored and must
# not be committed.

out=include/us_somo_gitinfo.h
tmp=include/.us_somo_gitinfo.h.tmp

branch=`git rev-parse --abbrev-ref HEAD 2>/dev/null`
commit=`git rev-parse --short=9 HEAD 2>/dev/null`
[ -n "$branch" ] || branch=unknown
[ -n "$commit" ] || commit=unknown
# "HEAD" means a detached checkout -- a tag, or a CI merge commit -- not a branch
[ "$branch" = "HEAD" ] && branch=detached
# keep the value a plain C string literal whatever the ref name contains
branch=`printf '%s' "$branch" | sed 's|[^A-Za-z0-9._/+-]|_|g'`

cat > "$tmp" <<EOH
// Generated by gitinfo.sh at build time: do not edit, do not commit.
#define US_SOMO_GIT_BRANCH "$branch"
#define US_SOMO_GIT_COMMIT "$commit"
EOH

if cmp -s "$tmp" "$out"; then
   rm -f "$tmp"
else
   mv -f "$tmp" "$out"
fi
