"""Clean package-target builds using real deployment scripts and tiny programs.

Qt deployment/scanning is stubbed; this verifies build dependencies and payload
selection, not native Qt runtime compatibility or NSIS/PKG installer behavior.
"""
from pathlib import Path
import subprocess
import re
import sys
import tarfile
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
MODULE = ROOT / "admin/cmake/packaging"


class AppPackageTest(unittest.TestCase):
    def run_command(self, *args, success=True):
        result = subprocess.run(args, text=True, capture_output=True)
        self.assertEqual(result.returncode == 0, success, result.stdout + result.stderr)
        return result.stdout + result.stderr

    def fixture(self, directory, platform, docs=True, multi=False):
        src = Path(directory) / "source"
        build = Path(directory) / "build"
        src.mkdir()
        (src / "main.c").write_text("int main(void) { return 0; }\n")
        (src / "deployer").write_text("#!/bin/sh\nexit 0\n")
        (src / "deployer").chmod(0o755)
        plugin = {"linux": "libqsqlite.so", "windows": "qsqlite.dll",
                  "macos": "libqsqlite.dylib"}[platform]
        for name in (f"plugins/sqldrivers/{plugin}", "plugins/platforms/qwindows.dll",
                     "plugins/platforms/libqcocoa.dylib", "runtime/sqlite3.dll"):
            p = src / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text("fixture")
        # Help is generated by a dependency, not prepopulated in the build tree.
        assistant_file = "assistant.exe" if platform == "windows" else "assistant"
        help_files = ["manual.qch", "manual.qhc", assistant_file]
        if platform == "macos":
            help_files.append("Assistant.app/Contents/MacOS/Assistant")
        (src / "help.cmake").write_text("\n".join(
            f'file(WRITE "${{OUTPUT}}/{name}" "fixture help")' for name in help_files))
        script = {"linux": "LinuxDeploy.cmake", "windows": "WinDeploy.cmake",
                  "macos": "MacDeploy.cmake"}[platform]
        (src / "deploy.cmake").write_text(f'''
set(APPLE {"TRUE" if platform == "macos" else "FALSE"})
set(WIN32 {"TRUE" if platform == "windows" else "FALSE"})
# Suppress unrelated optional downloads, retaining all other file operations.
function(file)
    if(ARGV0 STREQUAL "DOWNLOAD")
        set(${{ARGV4}} "1;fixture download disabled" PARENT_SCOPE)
    else()
        # Preserve literal shell text and semicolons in WRITE/COPY arguments.
        set(_call "_file(")
        math(EXPR _last "${{ARGC}} - 1")
        foreach(_i RANGE 0 ${{_last}})
            string(APPEND _call " [====[${{ARGV${{_i}}}}]====]")
        endforeach()
        cmake_language(EVAL CODE "${{_call}})")
        if(ARGV0 MATCHES "^(GLOB|GLOB_RECURSE)$")
            set(${{ARGV1}} "${{${{ARGV1}}}}" PARENT_SCOPE)
        elseif(ARGV0 MATCHES "^(READ|SIZE|STRINGS)$")
            set(${{ARGV2}} "${{${{ARGV2}}}}" PARENT_SCOPE)
        endif()
    endif()
endfunction()
include("{MODULE}/{platform}/{script}")
''')
        (src / "CMakeLists.txt").write_text(f'''
cmake_minimum_required(VERSION 3.21)
project(AppPackageFixture C)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${{CMAKE_BINARY_DIR}}/bin")
include("{MODULE}/AppPackage.cmake")
add_executable(us main.c)
add_executable(us_helpdaemon main.c)
add_executable(companion main.c)
set_target_properties(companion PROPERTIES OUTPUT_NAME us_renamed)
{"set_target_properties(us PROPERTIES MACOSX_BUNDLE TRUE)" if platform == "macos" else ""}
{"set_target_properties(us us_helpdaemon companion PROPERTIES SUFFIX .exe)" if platform == "windows" else ""}
us3_register_app_program_directory("${{CMAKE_CURRENT_SOURCE_DIR}}")
{"add_custom_target(documentation COMMAND ${CMAKE_COMMAND} -DOUTPUT=${CMAKE_BINARY_DIR}/bin -P ${CMAKE_SOURCE_DIR}/help.cmake)" if docs else ""}
set(QHELPGENERATOR_EXECUTABLE fixture)
us3_configure_app_package()
set(APPLE {"TRUE" if platform == "macos" else "FALSE"})
set(WIN32 {"TRUE" if platform == "windows" else "FALSE"})
set(US3_VERSION_STRING fixture)
set(US3_ARCH_LABEL fixture)
# Make the existing Linux scanner a no-op. No network/tool download is needed.
file(MAKE_DIRECTORY "${{CMAKE_BINARY_DIR}}/_tools/linuxdeploy/squashfs-root")
configure_file(deployer "${{CMAKE_BINARY_DIR}}/_tools/linuxdeploy/squashfs-root/AppRun" COPYONLY)
add_custom_target(deploy_{platform}
 COMMAND ${{CMAKE_COMMAND}}
   -DSTAGE_DIR=${{CMAKE_BINARY_DIR}}/_stage/UltraScan3
   -DBIN_DIR=${{CMAKE_RUNTIME_OUTPUT_DIRECTORY}}
   -DAPP_PROGRAM_MANIFEST=${{US3_APP_MANIFEST}}
   -DQCH_DIR=${{CMAKE_BINARY_DIR}}/bin
   -DASSISTANT_EXE=${{CMAKE_BINARY_DIR}}/bin/{assistant_file}
   -DWINDEPLOYQT=${{CMAKE_SOURCE_DIR}}/deployer
   -DMACDEPLOYQT=${{CMAKE_SOURCE_DIR}}/deployer
   -DVCPKG_BIN_DIR=${{CMAKE_SOURCE_DIR}}/runtime
   -DVCPKG_PLUGIN_DIR=${{CMAKE_SOURCE_DIR}}/plugins
   -DSOMO_BIN_DIR=${{CMAKE_BINARY_DIR}}/legacy-bin
   -DUS3_VERSION_STRING=fixture -DUS3_ARCH_LABEL=fixture
   -P ${{CMAKE_SOURCE_DIR}}/deploy.cmake
 DEPENDS us3_app_package_inputs VERBATIM)
'''+(f'include("{MODULE}/linux/LinuxPkg.cmake")\n' if platform == "linux" else f'''
add_custom_target(package_fixture
 COMMAND ${{CMAKE_COMMAND}} -E tar cJf "${{CMAKE_BINARY_DIR}}/fixture.tar.xz" --format=gnutar -- UltraScan3
 WORKING_DIRECTORY "${{CMAKE_BINARY_DIR}}/_stage"
 DEPENDS deploy_{platform} VERBATIM)
'''))
        args = ["cmake", "-S", str(src), "-B", str(build)]
        if multi:
            args += ["-G", "Ninja Multi-Config"]
        self.run_command(*args)
        # Simulate leftovers in both the output and the legacy SoMo source bin.
        for name in ("bin/us_stale", "bin/us_stale.exe", "legacy-bin/us_stale.exe",
                     "legacy-bin/us_stale.app/Contents/MacOS/us_stale"):
            path = build / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("stale executable")
        target = "package_linux_tarball" if platform == "linux" else "package_fixture"
        return src, build, target

    def test_clean_package_builds(self):
        platforms = ("linux", "windows", "macos") if sys.platform == "darwin" else ("linux", "windows")
        for platform in platforms:
            with self.subTest(platform=platform), tempfile.TemporaryDirectory(prefix="us3 package ") as d:
                _, build, target = self.fixture(d, platform)
                self.run_command("cmake", "--build", str(build), "--target", target, "--parallel", "3")
                with tarfile.open(next(build.glob("*.tar.xz"))) as archive:
                    names = archive.getnames()
                    self.assertFalse(any("us_stale" in name for name in names))
                    for binary in ("us", "us_helpdaemon", "us_renamed"):
                        suffix = ".exe" if platform == "windows" else ""
                        path = f"UltraScan3/bin/{binary}{suffix}"
                        if platform == "macos":
                            path = f"UltraScan3/bin/{binary}.app/Contents/MacOS/{binary}"
                        self.assertIn(path, names)
                    for help_file in ("manual.qch", "manual.qhc"):
                        self.assertIn(f"UltraScan3/bin/{help_file}", names)
                    assistant = "Assistant.app/Contents/MacOS/Assistant" if platform == "macos" else "assistant.exe" if platform == "windows" else "assistant"
                    self.assertIn(f"UltraScan3/bin/{assistant}", names)

    def test_platform_inventory(self):
        # Exercise the actual programs/ selection loop with tiny target declarations.
        selector = (ROOT / "programs/CMakeLists.txt").read_text().split(
            "if(NOT ENABLE_MPI)", 1)[1]
        selector = ("if(NOT ENABLE_MPI)" + selector).replace(
            "${CMAKE_SOURCE_DIR}/admin/cmake/packaging/AppPackage.cmake",
            str(MODULE / "AppPackage.cmake"))
        for apple, mpi in ((False, False), (True, False), (False, True)):
            with self.subTest(apple=apple, mpi=mpi), tempfile.TemporaryDirectory() as d:
                src = Path(d) / "source"
                src.mkdir()
                (src / "main.c").write_text("int main(void) { return 0; }\n")
                for program in (ROOT / "programs").glob("*/CMakeLists.txt"):
                    match = re.search(r"add_executable\(\s*(\w+)", program.read_text())
                    if match:
                        folder = src / program.parent.name
                        folder.mkdir()
                        (folder / "CMakeLists.txt").write_text(
                            f"add_executable({match[1]} ../main.c)\n")
                (src / "CMakeLists.txt").write_text(
                    "cmake_minimum_required(VERSION 3.21)\nproject(Inventory C)\n"
                    f"set(APPLE {'TRUE' if apple else 'FALSE'})\n"
                    f"set(ENABLE_MPI {'TRUE' if mpi else 'FALSE'})\n" + selector +
                    '\nget_property(inventory GLOBAL PROPERTY US3_APP_TARGETS)\n'
                    'file(WRITE "${CMAKE_BINARY_DIR}/inventory.txt" "${inventory}")\n')
                build = Path(d) / "build"
                self.run_command("cmake", "-S", str(src), "-B", str(build))
                inventory = (build / "inventory.txt").read_text().split(";")
                self.assertIn("us", inventory)
                self.assertIn("us_helpdaemon", inventory)
                self.assertEqual("us_mpi_analysis" in inventory, mpi)
                self.assertEqual("us_comproject_academic" in inventory, not apple)
                self.assertEqual("us_protocoldev" in inventory, not apple)
                self.assertEqual(len(inventory), 62 if apple else 71 if mpi else 70)

    def test_missing_assistant_fails(self):
        with tempfile.TemporaryDirectory() as d:
            src, build, target = self.fixture(d, "linux")
            help_script = src / "help.cmake"
            help_script.write_text("\n".join(
                line for line in help_script.read_text().splitlines() if "/assistant" not in line))
            output = self.run_command("cmake", "--build", str(build), "--target", target, success=False)
            self.assertIn("Required staged help component is missing", output)
            self.assertFalse(list(build.glob("*.tar.xz")))

    def test_missing_declared_executable_fails(self):
        with tempfile.TemporaryDirectory() as d:
            _, build, _ = self.fixture(d, "linux")
            output = self.run_command(
                "cmake", f"-DAPP_PROGRAM_MANIFEST={build}/app-package-.cmake",
                f"-DS_BIN={build}/stage/bin", "-P", str(MODULE / "StageAppPrograms.cmake"),
                success=False)
            self.assertIn("Required APP executable is missing", output)

    def test_no_documentation_target_fails(self):
        with tempfile.TemporaryDirectory() as d:
            _, build, target = self.fixture(d, "linux", docs=False)
            output = self.run_command("cmake", "--build", str(build), "--target", target, success=False)
            self.assertIn("APP packaging requires", output)
            self.assertFalse(list(build.glob("*.tar.xz")))

    def test_missing_help_output_fails(self):
        with tempfile.TemporaryDirectory() as d:
            src, build, target = self.fixture(d, "linux")
            (src / "help.cmake").write_text('file(WRITE "${OUTPUT}/manual.qch" "fixture")\n')
            self.run_command("cmake", "--build", str(build), "--target", target, success=False)
            self.assertFalse(list(build.glob("*.tar.xz")))

    def test_multi_config_manifest(self):
        with tempfile.TemporaryDirectory() as d:
            _, build, target = self.fixture(d, "linux", multi=True)
            self.run_command("cmake", "--build", str(build), "--config", "Release", "--target", target)
            manifest = (build / "app-package-Release.cmake").read_text()
            self.assertIn("/Release/us_renamed", manifest)
            with tarfile.open(next(build.glob("*.tar.xz"))) as archive:
                self.assertIn("UltraScan3/bin/us_renamed", archive.getnames())


if __name__ == "__main__":
    unittest.main()
